public struct SocialArchetype: Sendable, Equatable {
    public var key: String
    public var share: Double
    public var daily: Bool                     // one cohort per join DAY (tourists) instead of per join week
    public var lamX: [Double], lamY: [Double]  // levels per PLAYED day over the member quantile u
    public var lifeX: [Double], lifeY: [Double] // active life (days) over u; slope >= the join spread (containment)
    public var rho: Double                     // probability that a day is a play day
    public var sessMin: Int, sessMax: Int      // sessions on a play day
    public var firstLo: Double, firstHi: Double // install-session levels over u
    public var lapse: (lo: Double, hi: Double)? // lapsed phase after quitting (days over u)
    public var life2X: [Double]?, life2Y: [Double]?  // returners: second life (days over u)
    public var gap: (lo: Double, hi: Double)?  // returners: comeback gap (days, per cohort)
    public var custom: Double                  // share of members with a custom nickname
    public var avatarDefault: Double, avatarCustom: Double   // portrait probability (default name / custom name)
    /// Shipped model only (nil = the prototype): new members play (1 + beta) x their daily volume until `days` after the
    /// END of their cohort's join window (capped by each member's T1). One end per cohort keeps containment.
    public var honey: (beta: Double, days: Double)? = nil

    public static func == (a: SocialArchetype, b: SocialArchetype) -> Bool {
        a.key == b.key && a.share == b.share && a.daily == b.daily && a.lamX == b.lamX && a.lamY == b.lamY
            && a.lifeX == b.lifeX && a.lifeY == b.lifeY && a.rho == b.rho && a.sessMin == b.sessMin && a.sessMax == b.sessMax
            && a.firstLo == b.firstLo && a.firstHi == b.firstHi && a.lapse?.lo == b.lapse?.lo && a.lapse?.hi == b.lapse?.hi
            && a.life2X == b.life2X && a.life2Y == b.life2Y && a.gap?.lo == b.gap?.lo && a.gap?.hi == b.gap?.hi
            && a.custom == b.custom && a.avatarDefault == b.avatarDefault && a.avatarCustom == b.avatarCustom
            && a.honey?.beta == b.honey?.beta && a.honey?.days == b.honey?.days
    }
}

