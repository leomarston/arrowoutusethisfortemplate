/// How a device region code resolves on the v2 world (regions_v2.tsv): a table row, an alias of a row (a territory plays
/// on its parent's board: IC -> ES, GU -> US …) or a UN M.49 numeric region's representative row; `board` = the ISO of
/// the board it plays on.
public struct SocialRegion: Sendable, Equatable {
    public enum Kind: String, Sendable { case row, alias, numeric }
    public var kind: Kind
    public var board: String
}

/// PUBLISH B2 (PLAN-P §4.4, owner item 13; design/publish/social-intl.md §6): the v2 ("international") mechanisms of
/// design/social/tools/socialsim/v2.py, bit for bit. nil in the v1 models (reference, calibrated), which stay pinned by
/// their own fixtures.
///   M1 countryBlocks  a shared cohort no longer has ONE country: its members are split into contiguous blocks, one per row
///                     of its timezone band, apportioned inside `strata` equal strata (labels 'cblk' / 'cord'); a member's
///                     country and culture come from its block; levels and ids do not depend on the blocks
///   M2 jitter         u_j = (j + u01('uj', ck, j)) / n (u stays strictly increasing: containment and the binary searches
///                     stay exact, the evenly spaced ladders go)
///   M3 buckets/regions the country table v2 (200 rows, SocialIntlTables), 10 bands each with ONE schedule offset, and
///                     the region map (every isoRegions code -> a board)
///   M4 localByISO     the device-only LOCAL partition exists only for a 2-letter code no table knows; its cohort keys and
///                     name/avatar ids are salted with the 16-bit code; offset 0 and culture 'en' (never the device's)
///   M5 memberCulture  a member's name culture is drawn from its row's mix (label 'mcul' on the member's id)
///   M6/M7             native-script shares and the scaled popularity head live in the name style (SocialNameStyle.shipped)
///   M8 epoch          the world's own epoch (SocialWorldModel.epoch; the event calendar keeps SocialCalendar.epoch)
///   M9 shardTarget    a weekly cohort of E expected players is split into max(1, ⌊E / T + 0.5⌋) independent shards (key
///      minShards      ck + (k << 24)), at least `minShards[arch]` for regulars / returners
///   M10 lagMinutes    member j trails its cohort's clock by lag × (1 − u) minutes (0 = off, as shipped)
///   M11 rowTilt       inside M1's apportionment a row weighs weight × tilt[iso][archetype] (Turkey's archetype mix)
public struct SocialIntl: Sendable, Equatable {
    public var buckets: [String]
    public var bucketOffsets: [Int]
    public var regions: [String: SocialRegion]
    public var countryBlocks = true
    public var strata = 8
    public var jitter = true
    public var localByISO = true
    public var memberCulture = true
    public var shardTarget: [String: Double]? = nil
    public var minShards: [String: Int]? = nil
    public var lagMinutes = 0.0
    public var rowTilt: [String: [String: Double]] = [:]
}

