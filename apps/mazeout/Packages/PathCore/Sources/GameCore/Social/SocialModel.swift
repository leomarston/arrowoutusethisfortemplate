// ---------------------------------------------------------------------------------------------------------------------
// The v2 tables, parsed once from the generated TSV text (SocialIntlTables.swift). `Double(String)` / `Int(String)` restore
// exactly the values Python's float() / int() read from the same rows (data.use_countries_v2 / parse_mix).

extension SocialIntlTables {
    static func lines(_ tsv: String) -> [[String]] {
        tsv.split(separator: "\n").map { $0.split(separator: "\t", omittingEmptySubsequences: false).map(String.init) }
    }

    static let buckets: [(name: String, offset: Int)] = lines(bucketsTSV).map { ($0[0], Int($0[1])!) }

    /// data.parse_mix: 'nl:0.6,fr:0.4' -> [nl 0.6, fr 0.4]; 'en' -> [en 1.0].
    static func mix(_ s: String) -> [SocialCultureShare] {
        s.split(separator: ",").map { part in
            let kv = part.split(separator: ":")
            return kv.count == 2 ? SocialCultureShare(culture: String(kv[0]), weight: Double(String(kv[1]))!)
                : SocialCultureShare(culture: String(part), weight: 1.0)
        }
    }

    static let countries: [SocialCountryRow] = lines(countriesTSV).map { p in
        let m = mix(p[3])
        return SocialCountryRow(iso: p[0], weight: Double(p[1])!, offsetMinutes: Int(p[2])!, culture: m[0].culture, bucket: p[4],
                                mix: m)
    }

    static let regions: [String: SocialRegion] = {
        var out: [String: SocialRegion] = [:]
        for p in lines(regionsTSV) { out[p[0]] = SocialRegion(kind: SocialRegion.Kind(rawValue: p[1])!, board: p[2]) }
        return out
    }()
}
