    /// The board a device region code plays on, and whether it needs a device-only LOCAL partition.
    ///   v2 (socialsim/v2.py world_for_home): a row, alias or numeric region plays on the shared world (two friends see the
    ///   same boards) under its board's ISO; a 2-letter code no table knows gets its own LOCAL partition; anything else
    ///   (nil, empty, a malformed code) the fallback country.
    ///   v1: any 2-letter code (LOCAL when the table has no row for it), else the fallback (SocialState.setHomeIfNeeded).
    public func homeBoard(forRegion code: String?, fallback: String = "US") -> (iso: String, local: Bool) {
        let c = (code ?? "").uppercased()
        if let intl {
            if let r = intl.regions[c] { return (r.board, false) }
            if c.count == 2 && c.allSatisfy(\.isLetter) { return (c, true) }
            return (fallback, false)
        }
        guard c.count == 2 else { return (fallback, false) }
        return (c, !countries.contains(where: { $0.iso == c }))
    }

    /// The ISO of the board a stored home country plays on (v2 resolves an alias / numeric code; v1 keeps it).
    public func boardCountry(_ code: String) -> String {
        let c = code.uppercased()
        if let r = intl?.regions[c] { return r.board }
        return c
    }

    /// SPEC-social §2.5 containment condition: every life table rises at least the cohort's join spread per unit of u,
    /// and λ, first, lapse, life2 never fall in u (=> level is non-decreasing in u; every query is a binary search).
    public func containmentHolds() -> Bool {
        for a in archetypes {
            let span = a.daily ? 1.0 : 7.0
            for i in 1..<a.lifeX.count where (a.lifeY[i] - a.lifeY[i - 1]) / (a.lifeX[i] - a.lifeX[i - 1]) < span { return false }
            func rising(_ ys: [Double]) -> Bool { zip(ys, ys.dropFirst()).allSatisfy { $0 <= $1 } }
            if !rising(a.lamY) || a.firstLo > a.firstHi { return false }
            if let l = a.lapse, l.lo > l.hi { return false }
            if let y = a.life2Y, !rising(y) { return false }
        }
        return true
    }
