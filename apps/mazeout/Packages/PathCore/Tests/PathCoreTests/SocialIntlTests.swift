            guard c.p < wz.periodCount else { continue }
            guard let d = byCk[c.ck], d.n == c.n, d.gid0 == c.gid0,
                  wz.blk[d.blockLo..<d.blockHi].elementsEqual(W.blk[c.blockLo..<c.blockHi]) else { sharedSame = false; break }
            if c.n > 0 && wz.name(d, c.n - 1) != W.name(c, c.n - 1) { sharedSame = false; break }
        }
        XCTAssertTrue(sharedSame, "the shared world is byte-identical with a LOCAL partition")
    }

    // 19. every Locale.Region.isoRegions code resolves to a board; aliases point at rows; offsets within ±60 min
