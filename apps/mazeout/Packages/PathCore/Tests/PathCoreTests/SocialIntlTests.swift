    /// iso -> every member (brute force over the whole world; the definition the unit queries must equal).
    func membersByIso(_ W: SocialPopulation, _ isos: Set<String>, _ tMax: Double) -> [String: [(SocialCohort, Int)]] {
        var out: [String: [(SocialCohort, Int)]] = [:]
        for c in W.cohorts where c.n > 0 && c.join0 - c.span <= tMax {
            for j in 0..<c.n {
                let iso = W.isoOf(c, j)
                if isos.contains(iso) { out[iso, default: []].append((c, j)) }
            }
        }
        return out
    }

    // 15. country queries over (cohort, block) units = brute force: 10 countries × 3 times
    func testCountryQueriesEqualBruteForce() {
        let W = F.world("v2")
        let tNow = Self.tNow
        W.extend(to: tNow + 8 * 86_400)
        let times = [tNow - 50 * 86_400, tNow - 9 * 86_400 - 3 * 3600, tNow]
        let isos = ["US", "TR", "SK", "SI", "JP", "KR", "BE", "CH", "BR", "IS"]
        let mem = membersByIso(W, Set(isos), tNow)
        var bad: [String] = []
        for iso in isos {
            for t in times {
                var all: [(P: Double, gid: Int)] = []
                for (c, j) in mem[iso] ?? [] { if let P = W.progress(c, j, t) { all.append((P, W.gid(c, j))) } }
                all.sort { $0.P != $1.P ? $0.P > $1.P : $0.gid < $1.gid }
                for x in [1, 2, 11, 40, 62, 300] where all.filter({ 1 + SocialHash.floorInt($0.P) >= x }).count != W.countAtLeast(x, t, iso: iso) {
                    bad.append("count \(iso) \(t) \(x)")
                }
                if W.top(t, 40, iso: iso).map(\.gid) != all.prefix(40).map(\.gid) { bad.append("top \(iso) \(t)") }
                for x in [5, 30, 62] {
                    let (ab, be) = W.neighbours(x, t, above: 6, below: 6, iso: iso)
                    let wantA = all.filter { 1 + SocialHash.floorInt($0.P) >= x + 1 }.sorted { $0.P != $1.P ? $0.P < $1.P : $0.gid < $1.gid }.prefix(6)
                    let wantB = all.filter { 1 + SocialHash.floorInt($0.P) <= x }.sorted { $0.P != $1.P ? $0.P > $1.P : $0.gid > $1.gid }.prefix(6)
                    if ab.map(\.gid) != wantA.map(\.gid) || be.map(\.gid) != wantB.map(\.gid) { bad.append("nb \(iso) \(t) \(x)") }
                }
                SocTally.add(6 + 40 + 36)
            }
            XCTAssertGreaterThan(mem[iso]?.count ?? 0, 0, "\(iso) has players")
        }
        XCTAssertEqual(bad, [], "v2 country count / top / neighbours = brute force")
    }

    // 16. blocks partition every shared cohort into contiguous ranges of its band's rows; country sizes follow the weights
    func testBlocksPartitionEveryCohortAndSharesFollowTheWeights() throws {
        let W = F.world("v2")
        W.extend(to: Self.tNow + 8 * 86_400)
        let intl = try XCTUnwrap(W.intl)
        var ok = true
        var size: [String: Int] = [:], expect: [String: Double] = [:]
        for c in W.cohorts where !c.local {
            let rows = W.bucketRows[c.b]
            var pos = 0
            for bi in c.blockLo..<c.blockHi {
                let ri = Int(W.blk[bi] >> 16), s0 = Int(W.blk[bi] & 0xFFFF)
                let e0 = bi + 1 < c.blockHi ? Int(W.blk[bi + 1] & 0xFFFF) : c.n
                ok = ok && s0 == pos && e0 > s0 && ri < rows.count
                pos = e0
                size[rows[ri].iso, default: 0] += e0 - s0
            }
            ok = ok && pos == c.n
            let akey = c.arch.key
            let wts = rows.map { r in intl.rowTilt[r.iso].map { r.weight * ($0[akey] ?? 1.0) } ?? r.weight }
            let tw = wts.reduce(0, +)
            for (r, w) in zip(rows, wts) { expect[r.iso, default: 0] += Double(c.n) * w / tw }
        }
        XCTAssertTrue(ok, "blocks tile [0, n) in order")
        let tot = Double(size.values.reduce(0, +))
        var dev: [String] = []
        for iso in ["US", "GB", "DE", "BR", "TR", "JP", "SK", "SI"] {
            let want = expect[iso]! / tot, got = Double(size[iso] ?? 0) / tot
            if abs(got - want) > 0.08 * want + 3.0 / tot.squareRoot() { dev.append("\(iso) \(got / want)") }
        }
        XCTAssertEqual(dev, [], "country shares follow the table weights (\(Int(tot)) players)")
    }

