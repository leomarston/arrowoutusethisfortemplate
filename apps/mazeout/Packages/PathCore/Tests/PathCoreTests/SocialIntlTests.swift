    // 21. per-member culture follows the row's mix (BE nl .6 / fr .4, CH de .65, CA en .78, US es .0858)
    func testMemberCultureFollowsTheRowMix() {
        let W = F.world("v2")
        W.extend(to: Self.tNow + 8 * 86_400)
        var dev: [String] = []
        for (iso, cu, want) in [("BE", "nl", 0.6), ("CH", "de", 0.65), ("CA", "en", 0.78), ("US", "es", 0.0858)] {
            var n = 0, k = 0
            for c in W.cohorts where !c.local && c.join0 - c.span <= Self.tNow {
                for bi in c.blockLo..<c.blockHi where W.bucketRows[c.b][Int(W.blk[bi] >> 16)].iso == iso {
                    let s0 = Int(W.blk[bi] & 0xFFFF), e0 = bi + 1 < c.blockHi ? Int(W.blk[bi + 1] & 0xFFFF) : c.n
                    for j in s0..<e0 {
                        n += 1
                        if W.cultureOf(c, j) == cu { k += 1 }
                    }
                }
                if n > 6000 { break }
            }
            let got = Double(k) / Double(max(1, n))
            if n == 0 || abs(got - want) > 3.5 * (want * (1 - want) / Double(n)).squareRoot() + 0.01 { dev.append("\(iso) \(cu) \(n) \(got)") }
        }
        XCTAssertEqual(dev, [])
    }

    // 22. the world epoch: nobody joins before it; period 0 starts at it; world weeks share the event weeks' boundaries
